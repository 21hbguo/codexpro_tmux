import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { persistentToken } from "./tmux-credentials.mjs";
import { readExternalEndpoint, externalServerUrl, configureExternalEndpoint, selectLaunchEndpoint, fixedInstanceKey } from "./tmux-endpoint.mjs";
import { instanceLock, writePrivateJson, readPrivateJson } from "./tmux-lifecycle.mjs";

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "codexpro-token-test-"));
const key = "0123456789abcdef";
try {
  assert.throws(() => persistentToken(dir, key, { legacyRunning: true }), /older instance/);
  const imported = "a".repeat(48);
  assert.equal(persistentToken(dir, key, { legacyRunning: true, initialToken: imported }), imported);
  assert.equal(persistentToken(dir, key), imported);
  assert.throws(() => persistentToken(dir, key, { initialToken: "b".repeat(48) }), /differs/);
  const file = path.join(dir, key + ".token");
  assert.equal(fs.statSync(file).mode & 0o777, 0o600);
  const rotated = persistentToken(dir, key, { rotate: true });
  assert.notEqual(rotated, imported);
  assert.equal(persistentToken(dir, key), rotated);
  const other = persistentToken(dir, "fedcba9876543210");
  assert.notEqual(other, rotated);
  fs.chmodSync(file, 0o644);
  assert.throws(() => persistentToken(dir, key), /private regular file/);
  fs.unlinkSync(file);
  fs.symlinkSync(path.join(dir, "fedcba9876543210.token"), file);
  assert.throws(() => persistentToken(dir, key));
  const endpointFile = path.join(dir, "endpoint.json");
  assert.equal(readExternalEndpoint(endpointFile, dir), undefined);
  const config = { cwd: fs.realpathSync(dir), hostname: "bridge.example.com", port: 18790 };
  fs.writeFileSync(endpointFile, JSON.stringify(config), { mode: 0o600 });
  const selected = readExternalEndpoint(endpointFile, config.cwd);
  assert.deepEqual(selected, config);
  assert.deepEqual(selectLaunchEndpoint(selected, config.cwd), { cwd: config.cwd, external: config });
  assert.deepEqual(selectLaunchEndpoint(selected, path.dirname(config.cwd)), { cwd: config.cwd, external: config });
  assert.equal(fixedInstanceKey(selectLaunchEndpoint(selected, "/another-project").external), fixedInstanceKey(config));
  assert.throws(() => selectLaunchEndpoint(undefined, dir), /No fixed domain/);
  assert.throws(() => selectLaunchEndpoint(selected, dir, { quickTunnel: true }), /reserved/);
  assert.deepEqual(selectLaunchEndpoint(selected, "/other", { quickTunnel: true }), { cwd: "/other", external: undefined });
  assert.throws(() => selectLaunchEndpoint(selected, "/other", { localOnly: true, quickTunnel: true }), /Choose/);
  assert.deepEqual(configureExternalEndpoint(endpointFile, path.join(dir,"states"), config.hostname), config);
  assert.throws(() => configureExternalEndpoint(endpointFile, path.join(dir,"states"), "other.example.com"), /different endpoint/);
  assert.deepEqual(readExternalEndpoint(endpointFile), config);
  assert.equal(new URL(externalServerUrl(selected, imported)).searchParams.get("codexpro_token"), imported);
  assert.equal(new URL(externalServerUrl(selected, imported)).hostname, config.hostname);
  fs.writeFileSync(endpointFile, JSON.stringify({ ...config, hostname: "evil.example/path" }));
  assert.throws(() => readExternalEndpoint(endpointFile, dir), /Invalid external endpoint/);
  fs.writeFileSync(endpointFile, JSON.stringify({ ...config, port: 80 }));
  assert.throws(() => readExternalEndpoint(endpointFile, dir), /Invalid external endpoint/);
  fs.writeFileSync(endpointFile, JSON.stringify(config));
  fs.chmodSync(endpointFile, 0o644);
  assert.throws(() => readExternalEndpoint(endpointFile, dir), /private regular file/);
  fs.chmodSync(endpointFile, 0o600);
  fs.writeFileSync(endpointFile, JSON.stringify({ ...config, cwd: path.join(dir, "deleted") }));
  assert.equal(selectLaunchEndpoint(readExternalEndpoint(endpointFile), dir).cwd, path.join(dir, "deleted"));
  assert.equal(readExternalEndpoint(endpointFile).port, config.port);
  const freshDir = path.join(dir, "fresh");
  const freshFile = path.join(freshDir, "endpoint.json");
  const fresh = configureExternalEndpoint(freshFile, path.join(freshDir,"states"), "my.example.com");
  assert.equal(fresh.port, 8790);
  assert.equal(fs.statSync(freshFile).mode & 0o777, 0o600);
  assert.equal(fresh.cwd, path.join(freshDir,"tmux-fixed"));
  assert.deepEqual(configureExternalEndpoint(freshFile, path.join(freshDir,"states")), fresh);
  assert.equal(persistentToken(dir, fixedInstanceKey(fresh)), persistentToken(dir, fixedInstanceKey(selectLaunchEndpoint(fresh,"/another").external)));
  assert.throws(() => configureExternalEndpoint(path.join(dir,"bad.json"),path.join(dir,"states"),"https://evil.example/path"), /Invalid external endpoint/);
  const unlock = instanceLock(dir, key);
  assert.throws(() => instanceLock(dir, key), /locked/);
  unlock(); unlock();
  instanceLock(dir, key)();
  const metadata = path.join(dir, "meta.json");
  writePrivateJson(metadata, { commit: "example" });
  assert.deepEqual(readPrivateJson(metadata), { commit: "example" });
  assert.equal(fs.statSync(metadata).mode & 0o777, 0o600);
  console.log("tmux credential, endpoint and lifecycle smoke passed");
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
